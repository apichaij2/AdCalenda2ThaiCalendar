//
//  ข้อมูล C คือ เดือนไทย เดือนไทย ของวันที่ ๑ มกราคม
//// (C)  : เดือนไทย 1 เดือน อ้าย , เดือนไทย 2 เดือน ยี่
//
// อธิกสุรทิน	อธิกมาส	อธิกวาร ข้อมูล (D) แยกเป็น bit ในเลขฐาน 2
