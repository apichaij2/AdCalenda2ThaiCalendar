    2510, 721, 1722, 2714, 1020, 2122, 220, 1326, 2410, 622,
    1611, 2614, 922, 1910, 121, 1126, 2210, 422, 1410, 2515,
    722, 1710, 2810, 1026, 2110, 322, 1311, 2314, 622, 1611,
