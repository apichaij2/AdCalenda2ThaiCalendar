    420, 1522, 2510, 725, 1822, 2810, 1022, 2014, 321, 1322,
    2310, 524, 1722, 2710, 922, 1915, 120, 1222, 2211, 324,
    1522, 2510, 720, 1826, 2911, 1020, 2122, 224, 1422, 2411,
